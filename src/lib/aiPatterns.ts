/**
 * Правила для вкладки «Шаблоны» (SPEC §15.3). Это данные: список можно править без изменения кода.
 * Каждое найденное место — подсказка, а не приговор: обороты из списка встречаются и у людей.
 * Тексты пояснений живут здесь, рядом с шаблонами, чтобы правило читалось целиком (исключение из правила «строки в ru.ts»).
 *
 * Фразовое правило:
 *   id            — уникальное имя;
 *   pattern       — строка (ищется как есть, без учёта регистра, пробелы в ней значат любой пропуск, слово целиком)
 *                   или регулярное выражение (флаги g, i, u добавляются сами; пишите «е» вместо «ё»: текст перед поиском сворачивается);
 *   hint          — короткое пояснение, которое показывается по клику;
 *   paragraphStart — необязательно: совпадение считается, только если стоит в начале абзаца.
 */

export interface PhraseRule {
  id: string;
  pattern: string | RegExp;
  hint: string;
  paragraphStart?: boolean;
}

