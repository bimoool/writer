/**
 * Правила для вкладки «Шаблоны» (SPEC §15.3). Это данные: список можно править без изменения кода.
 * Каждое найденное место — подсказка, а не приговор: обороты из списка встречаются и у людей.
 * Тексты пояснений живут здесь, рядом с шаблонами, чтобы правило читалось целиком (исключение из правила «строки в ru.ts»).
 *
 * Как добавить правило:
 *   1. Выбери список: PHRASE_RULES (штампы, цвет «Шаблоны»), JUNK_RULES (словесный мусор) или STRUCTURE_RULES (строение текста, нужен код в aiCheck.ts).
 *   2. Добавь объект с полями из списка ниже. Обязательны id, pattern и hint; у мусора ещё category: 'junk', group и advice.
 *   3. Для слов, нормальных по одному, поставь minCount; для оборотов, которые бывают только в начале абзаца, paragraphStart.
 *   4. Прогони `CALIBRATION=1 npx vitest run src/lib/calibration.test.ts`: на живых текстах правило не должно срабатывать
 *      чаще одного раза на 100 слов (это проверяет тест). В комментарии над правилом напиши, на скольких обучающих текстах оно сработало.
 *   5. Не подгоняй шаблон под одну фразу: ищи оборот, который повторяется в разных ответах нейросетей.
 *
 * Фразовое правило:
 *   id            — уникальное имя;
 *   pattern       — строка (ищется как есть, без учёта регистра, пробелы в ней значат любой пропуск, слово целиком)
 *                   или регулярное выражение (флаги g, i, u добавляются сами; пишите «е» вместо «ё»: текст перед поиском сворачивается);
 *   hint          — короткое пояснение, которое показывается по клику;
 *   paragraphStart — необязательно: совпадение считается, только если стоит в начале абзаца;
 *   category      — 'cliche' (по умолчанию, штампы) или 'junk' (словесный мусор, свой цвет и свой список в интерфейсе);
 *   group         — для 'junk': ключ группы из JUNK_GROUPS;
 *   advice        — для 'junk': чем заменить;
 *   minCount      — необязательно: правило срабатывает, только если совпадений в тексте не меньше этого числа
 *                   (для слов, которые сами по себе нормальны, а мешают, когда их много).
 */

export interface PhraseRule {
  id: string;
  pattern: string | RegExp;
  hint: string;
  paragraphStart?: boolean;
  category?: 'cliche' | 'junk';
  group?: string;
  advice?: string;
  minCount?: number;
}

